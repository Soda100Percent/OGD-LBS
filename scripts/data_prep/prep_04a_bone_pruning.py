MANUAL_TEMPLATE_DEFAULT_STEM = "bone_reduced_001"
MANUAL_TEMPLATE_DEFAULT_ARMATURE = "Armature_Bone_Reduced_001"
MANUAL_VERSIONS_MANIFEST_NAME = "manifest.json"
MANUAL_VERSIONS_MANIFEST_SCHEMA = "ogd_lbs_manual_bone_reduced_versions_v1"


def utc_now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def save_blend(path: Path) -> None:
    print(f"\n💾 Saving to: {path}", flush=True)
    path.parent.mkdir(parents=True, exist_ok=True)

    result = bpy.ops.wm.save_as_mainfile(filepath=str(path))
    if result != {"FINISHED"}:
        raise RuntimeError(f"Failed to save blend file: {path}, result={result}")


def load_manual_versions_manifest(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {
            "schema": MANUAL_VERSIONS_MANIFEST_SCHEMA,
            "created_at_utc": utc_now_iso(),
            "updated_at_utc": utc_now_iso(),
            "templates": {},
            "notes": [
                "Templates are generated by Prep 04a as editable manual bone-reduction starting points.",
                "If a template file's mtime_ns/size still matches this manifest, Prep 05 may skip it as unmodified.",
                "Copied or renamed .blend files in this directory may be treated as additional manual variants.",
            ],
        }

    with path.open("r", encoding="utf-8") as f:
        obj = json.load(f)

    if not isinstance(obj, dict):
        raise RuntimeError(f"Manual versions manifest must be a JSON object: {path}")

    obj.setdefault("schema", MANUAL_VERSIONS_MANIFEST_SCHEMA)
    obj.setdefault("created_at_utc", utc_now_iso())
    obj.setdefault("templates", {})
    obj.setdefault("notes", [])

    if not isinstance(obj["templates"], dict):
        raise RuntimeError(f"Manual versions manifest field 'templates' must be an object: {path}")

    return obj


def dump_manual_versions_manifest(path: Path, obj: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    obj["updated_at_utc"] = utc_now_iso()

    with path.open("w", encoding="utf-8") as f:
        json.dump(obj, f, indent=4, ensure_ascii=False)


def file_metadata(path: Path) -> dict[str, Any]:
    stat = path.stat()
    return {
        "size": int(stat.st_size),
        "mtime": float(stat.st_mtime),
        "mtime_ns": int(stat.st_mtime_ns),
    }


def update_manual_template_manifest(
    *,
    manifest_path: Path,
    template_path: Path,
    template_armature_name: str,
    cleaned_full_blend_path: Path,
    cleaned_full_armature_name: str,
    original_armature_name: str,
) -> None:
    obj = load_manual_versions_manifest(manifest_path)

    rel_template = template_path.name
    meta = file_metadata(template_path)

    obj["templates"][rel_template] = {
        "kind": "generated_manual_template",
        "path": rel_template,
        "armature_name": template_armature_name,
        "generated_at_utc": utc_now_iso(),
        "generated_at_unix": time.time(),
        "generated_from_cleaned_full_blend": str(cleaned_full_blend_path.resolve()),
        "cleaned_full_armature_name": cleaned_full_armature_name,
        "original_armature_name": original_armature_name,
        "initial_file_metadata": meta,
        "skip_if_unmodified": True,
        "description": (
            "This file was generated automatically by Prep 04a as a starting "
            "point for optional manual bone reduction. If its file metadata is "
            "unchanged, it can be skipped by Fitbox export."
        ),
    }

    dump_manual_versions_manifest(manifest_path, obj)


def create_manual_bone_reduced_template(
    *,
    manual_versions_dir: Path,
    template_stem: str,
    template_armature_name: str,
    cleaned_full_armature_name: str,
    original_armature_name: str,
    cleaned_full_blend_path: Path,
    overwrite: bool,
) -> Path | None:
    """
    Save an editable manual bone-reduction template.

    The current scene is expected to have already been saved as cleaned_full.
    This function then renames Armature_Cleaned_Full to the template armature
    name and saves a separate .blend in manual_versions_dir.

    It does not attempt to restore the in-memory scene afterwards because the
    script ends after this step. The cleaned_full .blend on disk is already
    saved before the rename.
    """
    manual_versions_dir.mkdir(parents=True, exist_ok=True)

    template_stem = str(template_stem).strip()
    if not template_stem:
        raise RuntimeError("manual template stem cannot be empty.")

    if template_stem.endswith(".blend"):
        template_path = manual_versions_dir / template_stem
    else:
        template_path = manual_versions_dir / f"{template_stem}.blend"

    if template_path.exists() and not overwrite:
        print("\n⚠️ Manual template already exists; not overwriting:", flush=True)
        print(f"   {template_path}", flush=True)
        print("   Use --overwrite_manual_template if you really want to regenerate it.", flush=True)
        return None

    cleaned = bpy.data.objects.get(cleaned_full_armature_name)
    if cleaned is None or cleaned.type != "ARMATURE":
        raise RuntimeError(
            f"Cannot create manual template: cleaned-full armature not found: "
            f"{cleaned_full_armature_name}"
        )

    existing_variant = bpy.data.objects.get(template_armature_name)
    if existing_variant is not None and existing_variant is not cleaned:
        raise RuntimeError(
            f"Cannot rename cleaned-full armature to {template_armature_name!r}: "
            "another object with that name already exists."
        )

    print("\n🧑‍🔧 Creating editable manual bone-reduction template...", flush=True)
    print(f"   Template blend:     {template_path}", flush=True)
    print(f"   Template armature:  {template_armature_name}", flush=True)

    cleaned.name = template_armature_name
    cleaned.data.name = template_armature_name

    update_view_layer()
    save_blend(template_path)

    manifest_path = manual_versions_dir / MANUAL_VERSIONS_MANIFEST_NAME
    update_manual_template_manifest(
        manifest_path=manifest_path,
        template_path=template_path,
        template_armature_name=template_armature_name,
        cleaned_full_blend_path=cleaned_full_blend_path,
        cleaned_full_armature_name=cleaned_full_armature_name,
        original_armature_name=original_armature_name,
    )

    print(f"   Manual versions manifest updated: {manifest_path}", flush=True)
    return template_path


def print_manual_4b_prompt(
    *,
    output_blend: Path,
    manual_versions_dir: Path,
    template_path: Path | None,
    cleaned_full_name: str,
    template_armature_name: str,
) -> None:
    print("\n" + "=" * 96, flush=True)
    print("🧑‍🔧 Optional manual Step 04b: create bone-reduced versions", flush=True)
    print("=" * 96, flush=True)
    print("Prep 04a has created the cleaned-full reference blend:", flush=True)
    print(f"   {output_blend}", flush=True)
    print(f"   cleaned-full armature: {cleaned_full_name}", flush=True)
    print("", flush=True)

    if template_path is not None:
        print("Prep 04a also created an editable manual template:", flush=True)
        print(f"   {template_path}", flush=True)
        print(f"   template armature: {template_armature_name}", flush=True)
        print("", flush=True)
        print("If you edit this file and save it, later Fitbox export can include it.", flush=True)
        print("If it remains unmodified, later Fitbox export should skip it.", flush=True)
    else:
        print("No new manual template was created in this run.", flush=True)
        print("This usually means the default template file already existed.", flush=True)

    print("", flush=True)
    print("For multiple manual reduced variants, duplicate or save copies under:", flush=True)
    print(f"   {manual_versions_dir}", flush=True)
    print("Suggested names:", flush=True)
    print("   bone_reduced_001.blend", flush=True)
    print("   bone_reduced_002.blend", flush=True)
    print("   bone_reduced_wingless.blend", flush=True)
    print("", flush=True)
    print("Future Fitbox export should include cleaned_full plus all modified/manual", flush=True)
    print("bone-reduced versions, using filename or armature suffix to distinguish them.", flush=True)
    print("=" * 96, flush=True)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Prep 04a: create cleaned-full armature branch and editable manual template."
    )

    parser.add_argument("--input_blend", type=str, required=True)
    parser.add_argument(
        "--output_blend",
        type=str,
        default=None,
        help="Output cleaned-full blend. Default: <work_dir>/<base_stem>_prep_04a_cleaned_full.blend",
    )
    parser.add_argument(
        "--manual_versions_dir",
        type=str,
        default=None,
        help="Directory for optional manual 4b reduced versions. Default: <work_dir>/bone_reduced_versions/",
    )

    parser.add_argument("--weight_eps", type=float, default=1e-8)
    parser.add_argument("--min_bone_length_ratio", type=float, default=0.02)

    parser.add_argument("--original_armature_name", type=str, default="Armature_Original")
    parser.add_argument("--cleaned_full_armature_name", type=str, default="Armature_Cleaned_Full")

    parser.add_argument(
        "--manual_template_stem",
        type=str,
        default=MANUAL_TEMPLATE_DEFAULT_STEM,
        help="Editable manual template blend stem/name. Default: bone_reduced_001",
    )
    parser.add_argument(
        "--manual_template_armature_name",
        type=str,
        default=MANUAL_TEMPLATE_DEFAULT_ARMATURE,
        help="Armature name inside the editable manual template. Default: Armature_Bone_Reduced_001",
    )
    parser.add_argument(
        "--no_manual_template",
        action="store_true",
        help="Do not create the editable manual bone-reduced template.",
    )
    parser.add_argument(
        "--overwrite_manual_template",
        action="store_true",
        help="Overwrite existing manual template file. Use with care; this may overwrite manual edits.",
    )

    args = parser.parse_args(script_argv())

    ctx = make_data_prep_context(args.input_blend)

    input_path = ctx.resolve_input(
        "input_blend",
        args.input_blend,
        None,
        expected_type="file",
    )
    output_path = ctx.resolve_output(
        "output_blend",
        args.output_blend,
        prep_04a_output_blend_rel(ctx),
        expected_type="file",
    )
    manual_versions_dir = ctx.resolve_output(
        "manual_versions_dir",
        args.manual_versions_dir,
        prep_04b_manual_versions_dir_rel(ctx),
        expected_type="dir",
    )

    ctx.print_and_validate("Prep 04a: Cleaned-Full Armature Preparation")

    print(f"📂 Loading: {input_path}", flush=True)
    result = bpy.ops.wm.open_mainfile(filepath=str(input_path))
    if result != {"FINISHED"}:
        raise RuntimeError(f"Failed to open blend file: {input_path}, result={result}")

    ensure_object_mode()

    armature = find_armature(required=True, prefer_name="Armature")
    if armature is None:
        raise RuntimeError("No ARMATURE found in the scene.")

    print("\n🎬 Preserving animation data, meshes, modifiers, and vertex groups.", flush=True)
    for arm in [obj for obj in bpy.data.objects if obj.type == "ARMATURE"]:
        arm.data.pose_position = "POSE"

    print("\n📊 Step 1: Scanning all mesh vertex groups for effective weights...", flush=True)
    effective_vgs = collect_effective_vertex_group_names_from_all_meshes(
        eps=float(args.weight_eps)
    )
    print(f"   Effective vertex groups across all meshes: {len(effective_vgs)}", flush=True)

    print("\n📊 Step 2: Classifying bones for automatic cleaned-full preparation...", flush=True)
    classes = classify_bones(
        armature,
        effective_vgs=effective_vgs,
        min_length_ratio=float(args.min_bone_length_ratio),
    )

    keep_effective = classes["KEEP_EFFECTIVE"]
    delete_tiny = classes["DELETE_TINY_LENGTH"]
    delete_invalid = classes["DELETE_INVALID_WEIGHT"]
    delete_non_deform = classes["DELETE_NON_DEFORM"]

    delete_names = delete_tiny | delete_invalid | delete_non_deform

    print(f"   Total bones:                      {len(armature.data.bones)}", flush=True)
    print(f"   ✅ Keep effective valid length:    {len(keep_effective)}", flush=True)
    print(f"   ❌ Delete tiny length:             {len(delete_tiny)}", flush=True)
    print(f"   ❌ Delete invalid weight:          {len(delete_invalid)}", flush=True)
    print(f"   ❌ Delete non-deform:              {len(delete_non_deform)}", flush=True)
    print(f"   ❌ Delete total union:             {len(delete_names)}", flush=True)

    arm_orig, arm_cleaned_full = duplicate_and_prune_cleaned_full_armature(
        armature=armature,
        delete_names=delete_names,
        original_name=str(args.original_armature_name),
        cleaned_full_name=str(args.cleaned_full_armature_name),
    )

    print("\n🧩 Mesh / modifier data preserved. Vertex groups are NOT removed.", flush=True)
    print("   Mesh modifiers are not redirected in Prep 04a.", flush=True)
    print(f"   Original armature object:     {arm_orig.name}", flush=True)
    print(f"   Cleaned-full armature object: {arm_cleaned_full.name}", flush=True)

    update_view_layer()

    save_blend(output_path)

    template_path: Path | None = None

    if args.no_manual_template:
        print("\n🧑‍🔧 Manual template generation disabled by --no_manual_template.", flush=True)
    else:
        template_path = create_manual_bone_reduced_template(
            manual_versions_dir=manual_versions_dir,
            template_stem=str(args.manual_template_stem),
            template_armature_name=str(args.manual_template_armature_name),
            cleaned_full_armature_name=str(args.cleaned_full_armature_name),
            original_armature_name=str(args.original_armature_name),
            cleaned_full_blend_path=output_path,
            overwrite=bool(args.overwrite_manual_template),
        )

    print_manual_4b_prompt(
        output_blend=output_path,
        manual_versions_dir=manual_versions_dir,
        template_path=template_path,
        cleaned_full_name=str(args.cleaned_full_armature_name),
        template_armature_name=str(args.manual_template_armature_name),
    )

    print("\n🎉 Prep 04a cleaned-full preparation done.", flush=True)


if __name__ == "__main__":
    main()
